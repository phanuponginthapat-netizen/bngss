DROP FUNCTION IF EXISTS public.can_access_eform_attachment(uuid, uuid) CASCADE;
CREATE OR REPLACE FUNCTION public.can_access_eform_attachment(_eform_id uuid, _user_id uuid)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.eforms e
    WHERE e.id = _eform_id
      AND (
        e.sender_id = _user_id
        OR EXISTS (
          SELECT 1
          FROM public.eform_recipients r
          WHERE r.eform_id = e.id
            AND r.recipient_id = _user_id
        )
        OR public.has_role(_user_id, 'admin'::public.app_role)
        OR public.has_role(_user_id, 'director'::public.app_role)
      )
  );
$$;
