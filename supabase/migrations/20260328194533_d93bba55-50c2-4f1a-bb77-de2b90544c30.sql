-- Attendance
CREATE TABLE IF NOT EXISTS public.attendance (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  student_id uuid REFERENCES public.students(id) ON DELETE CASCADE,
  subject_id uuid REFERENCES public.subjects(id) ON DELETE SET NULL,
  attendance_date date NOT NULL DEFAULT CURRENT_DATE,
  status text NOT NULL DEFAULT 'present',
  notes text,
  recorded_by text,
  academic_year integer DEFAULT EXTRACT(year FROM now()),
  semester integer,
  created_at timestamptz NOT NULL DEFAULT now()
);
-- Behavior records
CREATE TABLE IF NOT EXISTS public.behavior_records (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  student_id uuid REFERENCES public.students(id) ON DELETE CASCADE,
  record_date date NOT NULL DEFAULT CURRENT_DATE,
  behavior_type text NOT NULL DEFAULT 'positive',
  description text NOT NULL,
  points integer DEFAULT 0,
  recorded_by text,
  created_at timestamptz NOT NULL DEFAULT now()
);
-- Student leaves
CREATE TABLE IF NOT EXISTS public.student_leaves (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  student_id uuid REFERENCES public.students(id) ON DELETE CASCADE,
  leave_type text NOT NULL DEFAULT 'sick',
  start_date date NOT NULL,
  end_date date NOT NULL,
  reason text,
  status text NOT NULL DEFAULT 'pending',
  approved_by text,
  created_at timestamptz NOT NULL DEFAULT now()
);
-- Student screenings
CREATE TABLE IF NOT EXISTS public.student_screenings (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  student_id uuid REFERENCES public.students(id) ON DELETE CASCADE,
  academic_year integer DEFAULT EXTRACT(year FROM now()),
  screening_type text NOT NULL DEFAULT 'general',
  category text NOT NULL DEFAULT 'normal',
  economic_status text,
  protection_status text,
  notes text,
  screened_by text,
  created_at timestamptz NOT NULL DEFAULT now()
);
-- Homeroom records
CREATE TABLE IF NOT EXISTS public.homeroom_records (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  student_id uuid REFERENCES public.students(id) ON DELETE CASCADE,
  classroom_id uuid REFERENCES public.classrooms(id) ON DELETE SET NULL,
  academic_year integer DEFAULT EXTRACT(year FROM now()),
  semester integer,
  advisor_notes text,
  parent_contact text,
  visit_date date,
  created_at timestamptz NOT NULL DEFAULT now()
);
-- SDQ records
CREATE TABLE IF NOT EXISTS public.sdq_records (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  student_id uuid REFERENCES public.students(id) ON DELETE CASCADE,
  academic_year integer DEFAULT EXTRACT(year FROM now()),
  emotional_score integer DEFAULT 0,
  conduct_score integer DEFAULT 0,
  hyperactivity_score integer DEFAULT 0,
  peer_score integer DEFAULT 0,
  prosocial_score integer DEFAULT 0,
  total_difficulty integer DEFAULT 0,
  assessment_by text,
  assessment_type text DEFAULT 'teacher',
  created_at timestamptz NOT NULL DEFAULT now()
);
-- Home visits
CREATE TABLE IF NOT EXISTS public.home_visits (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  student_id uuid REFERENCES public.students(id) ON DELETE CASCADE,
  visit_date date NOT NULL DEFAULT CURRENT_DATE,
  visitor_name text NOT NULL,
  home_condition text,
  student_condition text,
  family_status text,
  recommendations text,
  created_at timestamptz NOT NULL DEFAULT now()
);
-- Health records
CREATE TABLE IF NOT EXISTS public.health_records (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  student_id uuid REFERENCES public.students(id) ON DELETE CASCADE,
  visit_date date NOT NULL DEFAULT CURRENT_DATE,
  symptoms text NOT NULL,
  treatment text,
  nurse_name text,
  follow_up_needed boolean DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);
-- News posts
CREATE TABLE IF NOT EXISTS public.news_posts (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  title text NOT NULL,
  content text,
  category text NOT NULL DEFAULT 'general',
  is_published boolean DEFAULT false,
  published_at timestamptz,
  author text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
-- Documents (e-saraban)
CREATE TABLE IF NOT EXISTS public.documents (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  doc_number text NOT NULL,
  title text NOT NULL,
  from_department text,
  to_department text,
  doc_date date NOT NULL DEFAULT CURRENT_DATE,
  doc_type text NOT NULL DEFAULT 'incoming',
  status text NOT NULL DEFAULT 'pending',
  notes text,
  created_at timestamptz NOT NULL DEFAULT now()
);
-- Emergency broadcasts
CREATE TABLE IF NOT EXISTS public.emergency_broadcasts (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  title text NOT NULL,
  message text NOT NULL,
  severity text NOT NULL DEFAULT 'info',
  is_active boolean DEFAULT true,
  sent_at timestamptz NOT NULL DEFAULT now(),
  sent_by text,
  created_at timestamptz NOT NULL DEFAULT now()
);
-- Vaccine records
CREATE TABLE IF NOT EXISTS public.vaccine_records (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  student_id uuid REFERENCES public.students(id) ON DELETE CASCADE,
  vaccine_name text NOT NULL,
  dose_number integer DEFAULT 1,
  date_administered date NOT NULL DEFAULT CURRENT_DATE,
  administered_by text,
  lot_number text,
  notes text,
  created_at timestamptz NOT NULL DEFAULT now()
);
-- Personnel
CREATE TABLE IF NOT EXISTS public.personnel (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  employee_code text NOT NULL UNIQUE,
  prefix text DEFAULT 'นาย',
  first_name text NOT NULL,
  last_name text NOT NULL,
  position text NOT NULL DEFAULT 'ครู',
  department text NOT NULL DEFAULT 'วิชาการ',
  phone text,
  email text,
  status text NOT NULL DEFAULT 'active',
  hire_date date,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
-- Time clock
CREATE TABLE IF NOT EXISTS public.time_clock (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  personnel_id uuid REFERENCES public.personnel(id) ON DELETE CASCADE,
  clock_date date NOT NULL DEFAULT CURRENT_DATE,
  clock_in timestamptz,
  clock_out timestamptz,
  status text NOT NULL DEFAULT 'normal',
  notes text,
  created_at timestamptz NOT NULL DEFAULT now()
);
-- Staff leaves
CREATE TABLE IF NOT EXISTS public.staff_leaves (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  personnel_id uuid REFERENCES public.personnel(id) ON DELETE CASCADE,
  leave_type text NOT NULL DEFAULT 'personal',
  start_date date NOT NULL,
  end_date date NOT NULL,
  reason text,
  status text NOT NULL DEFAULT 'pending',
  approved_by text,
  created_at timestamptz NOT NULL DEFAULT now()
);
-- Staff evaluations
CREATE TABLE IF NOT EXISTS public.staff_evaluations (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  personnel_id uuid REFERENCES public.personnel(id) ON DELETE CASCADE,
  evaluator_name text NOT NULL,
  academic_year integer DEFAULT EXTRACT(year FROM now()),
  evaluation_type text NOT NULL DEFAULT 'performance',
  score numeric DEFAULT 0,
  max_score numeric DEFAULT 100,
  comments text,
  created_at timestamptz NOT NULL DEFAULT now()
);
-- Substitute teaching
CREATE TABLE IF NOT EXISTS public.substitute_teaching (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  original_teacher text NOT NULL,
  substitute_teacher text NOT NULL,
  subject_id uuid REFERENCES public.subjects(id) ON DELETE SET NULL,
  classroom_id uuid REFERENCES public.classrooms(id) ON DELETE SET NULL,
  teaching_date date NOT NULL DEFAULT CURRENT_DATE,
  period text NOT NULL,
  status text NOT NULL DEFAULT 'pending',
  notes text,
  created_at timestamptz NOT NULL DEFAULT now()
);
-- Admissions
CREATE TABLE IF NOT EXISTS public.admissions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  academic_year integer DEFAULT EXTRACT(year FROM now()),
  applicant_prefix text DEFAULT 'ด.ช.',
  applicant_first_name text NOT NULL,
  applicant_last_name text NOT NULL,
  grade_applying text NOT NULL,
  previous_school text,
  parent_name text,
  parent_phone text,
  exam_room text,
  exam_seat integer,
  exam_score numeric,
  status text NOT NULL DEFAULT 'registered',
  applied_at timestamptz NOT NULL DEFAULT now(),
  created_at timestamptz NOT NULL DEFAULT now()
);
-- Homework assignments
CREATE TABLE IF NOT EXISTS public.homework_assignments (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  subject_id uuid REFERENCES public.subjects(id) ON DELETE CASCADE,
  classroom_id uuid REFERENCES public.classrooms(id) ON DELETE SET NULL,
  title text NOT NULL,
  description text,
  due_date date,
  assigned_by text,
  status text NOT NULL DEFAULT 'active',
  created_at timestamptz NOT NULL DEFAULT now()
);
-- Schedules
CREATE TABLE IF NOT EXISTS public.schedules (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  classroom_id uuid REFERENCES public.classrooms(id) ON DELETE CASCADE,
  subject_id uuid REFERENCES public.subjects(id) ON DELETE CASCADE,
  day_of_week integer NOT NULL,
  period integer NOT NULL,
  start_time time,
  end_time time,
  teacher_name text,
  academic_year integer DEFAULT EXTRACT(year FROM now()),
  semester integer,
  created_at timestamptz NOT NULL DEFAULT now()
);
-- Early childhood development
