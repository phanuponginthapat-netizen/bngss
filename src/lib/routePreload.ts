const done = new Set<string>();
export function preloadRoute(url: string) {
  const path = url.split("?")[0].split("#")[0];
  if (done.has(path)) return;
  const fn = loaders[path];
  if (!fn) return;
  done.add(path);
  fn().catch(() => done.delete(path));
}
