CREATE OR REPLACE FUNCTION public.check_and_grant_badges()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  b RECORD; total_pts numeric := 0; total_dep int := 0; total_wt numeric := 0;
BEGIN
  IF NEW.student_id IS NOT NULL THEN
    SELECT COALESCE(total_points,0) INTO total_pts FROM public.garbage_student_points WHERE student_id = NEW.student_id;
    SELECT COUNT(*), COALESCE(SUM(quantity),0) INTO total_dep, total_wt FROM public.garbage_deposits WHERE student_id = NEW.student_id;
    FOR b IN SELECT * FROM public.garbage_badges WHERE is_active LOOP
      IF (b.criteria_type='total_points' AND total_pts >= b.criteria_value)
         OR (b.criteria_type='total_deposits' AND total_dep >= b.criteria_value)
         OR (b.criteria_type='total_weight' AND total_wt >= b.criteria_value) THEN
        INSERT INTO public.garbage_user_badges (badge_id, student_id) VALUES (b.id, NEW.student_id) ON CONFLICT DO NOTHING;
      END IF;
    END LOOP;
  ELSIF NEW.personnel_id IS NOT NULL THEN
    SELECT COALESCE(total_points,0) INTO total_pts FROM public.garbage_personnel_points WHERE personnel_id = NEW.personnel_id;
    SELECT COUNT(*), COALESCE(SUM(quantity),0) INTO total_dep, total_wt FROM public.garbage_deposits WHERE personnel_id = NEW.personnel_id;
    FOR b IN SELECT * FROM public.garbage_badges WHERE is_active LOOP
      IF (b.criteria_type='total_points' AND total_pts >= b.criteria_value)
         OR (b.criteria_type='total_deposits' AND total_dep >= b.criteria_value)
         OR (b.criteria_type='total_weight' AND total_wt >= b.criteria_value) THEN
        INSERT INTO public.garbage_user_badges (badge_id, personnel_id) VALUES (b.id, NEW.personnel_id) ON CONFLICT DO NOTHING;
      END IF;
    END LOOP;
  END IF;
  RETURN NEW;
END $$;
