-- Ensure the existing trigger still exists and is active
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_trigger
    WHERE tgname = 'trg_prevent_self_student_code_change'
      AND tgrelid = 'public.profiles'::regclass
